/**
 * Make the Draco decoder of three.js load under the CSP of the app.
 *
 * DRACOLoader of three.js decodes in Web Workers. It reads the decoder JavaScript as text, adds the worker code and
 * starts each worker from a Blob URL. The CSP of the app has `worker-src 'self'` and Trusted Types, so a Blob worker
 * does not start. The decoder JavaScript (`examples/jsm/libs/draco/gltf/draco_wasm_wrapper.js`) is an Emscripten build
 * with the WebIDL binder: it has no `eval` and no `new Function`. Thus the render worker can run it in its own thread.
 *
 * This script writes a copy of the decoder JavaScript as an ES module (`export default DracoDecoderModule`), so the
 * Vite dev server, the production bundle and Bun load it the same way. The decoder of @scenity/render (`draco.ts`)
 * gives it the WASM bytes. The WASM file does not change.
 *
 *   bun packages/assets/src/build/patchDraco.ts <target>           write the copy (the repo: packages/render/src/vendor/draco_wasm_wrapper.js)
 *   bun packages/assets/src/build/patchDraco.ts <target> --check   fail when the copy is not current (CI; a three.js update)
 *
 * The package of the target resolves three.js, so the copy comes from the three.js version of that package. A part to
 * replace that is not in the source (a new Emscripten version) stops the script. Then read the new source.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { resolve } from "node:path";

/** The source file of three.js that the package of `target` resolves (the package of the copy has three.js). */
export function sourceOf(target: string): string {
  return createRequire(resolve(target)).resolve("three/examples/jsm/libs/draco/gltf/draco_wasm_wrapper.js");
}

/** The export of the source for CommonJS and AMD; the copy is an ES module. */
const EXPORT =
  '"object"===typeof exports&&"object"===typeof module?module.exports=DracoDecoderModule:"function"===typeof define&&define.amd?define([],function(){return DracoDecoderModule}):"object"===typeof exports&&(exports.DracoDecoderModule=DracoDecoderModule);';

const HEADER = `// Generated by packages/assets/src/build/patchDraco.ts from three/examples/jsm/libs/draco/gltf/draco_wasm_wrapper.js
// (the Draco decoder of Google LLC, Apache-2.0; Emscripten glue). Do not edit. The copy is an ES module: the render
// worker runs the decoder in its own thread, with no Blob worker and no dynamic code.
/* eslint-disable */
`;

/** The patched decoder source. Throws when the part to replace is not in the source, or on dynamic code. */
export function patchedDecoder(source: string): string {
  const count = source.split(EXPORT).length - 1;
  if (count !== 1) throw new Error(`patch-draco: the export found ${String(count)} times (expected 1)`);
  const text = source.replace(EXPORT, () => "export default DracoDecoderModule;");
  if (/new Function|\bFunction\(|\beval\(|importScripts\(|createObjectURL/.test(text.replace(/\w+Function\(/g, ""))) {
    throw new Error("patch-draco: the decoder has dynamic code or a Blob URL");
  }
  return HEADER + text;
}

/** Write the copy at `target`, or with `check` only compare it. Returns false when the check finds an old copy. */
export function writeCopy(target: string, check: boolean): boolean {
  const wanted = patchedDecoder(readFileSync(sourceOf(target), "utf8"));
  if (check) {
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch {
      // A missing file is not current.
    }
    if (current === wanted) return true;
    console.error(`${target} is not current. Run: bun packages/assets/src/build/patchDraco.ts ${target}`);
    return false;
  }
  writeFileSync(target, wanted);
  console.log(`patch-draco: wrote ${target}`);
  return true;
}

if (import.meta.main) {
  const target = process.argv.slice(2).find((arg) => !arg.startsWith("--"));
  if (target === undefined) {
    console.error("usage: bun packages/assets/src/build/patchDraco.ts <target file> [--check]");
    process.exit(2);
  }
  if (!writeCopy(target, process.argv.includes("--check"))) process.exit(1);
}
