/**
 * Make the Basis Universal transcoder of Three.js run under the CSP of the app.
 *
 * The transcoder JavaScript of Three.js (`examples/jsm/libs/basis/basis_transcoder.js`) is an Emscripten build
 * with embind. Embind makes its function wrappers with `new Function(...)`. The CSP of the app has no
 * 'unsafe-eval' and has `require-trusted-types-for 'script'`, so the browser blocks them, and all KTX2 textures
 * fail. This script writes a copy in which closures replace the two dynamic parts and do the same work (as the
 * Emscripten build option DYNAMIC_EXECUTION=0 does). The parts are the invoker of a bound function
 * (`craftInvokerFunction`) and the method caller of `emval` (`__emval_get_method_caller`). The copy is an ES module
 * (`export default`), so the Vite dev server, the production bundle and Bun load it the same way. The WASM file does
 * not change.
 *
 *   bun packages/assets/src/build/patchBasis.ts <target>           write the copy (the repo: packages/render/src/vendor/basis_transcoder.js)
 *   bun packages/assets/src/build/patchBasis.ts <target> --check   fail when the copy is not current (CI; a Three.js update)
 *
 * The package of the target resolves three.js, so the copy comes from the three.js version of that package.
 *
 * A replaced part that is not in the source (a new Emscripten version) stops the script. Then read the new source
 * and write the new replacement.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { resolve } from "node:path";

/** The source file of three.js that the package of `target` resolves (the package of the copy has three.js). */
export function sourceOf(target: string): string {
  return createRequire(resolve(target)).resolve("three/examples/jsm/libs/basis/basis_transcoder.js");
}

interface Patch {
  readonly name: string;
  readonly find: string;
  readonly replace: string;
}

const PATCHES: readonly Patch[] = [
  {
    name: "craftInvokerFunction",
    find: "let[args,invokerFnBody]=createJsInvoker(argTypes,isClassMethodFunc,returns,isAsync);args.push(invokerFnBody);var invokerFn=newFunc(Function,args)(...closureArgs);return createNamedFunction(humanName,invokerFn)}",
    replace: [
      "var invokerFn=function(...callArgs){",
      "if(callArgs.length!==argCount-2){throwBindingError(`function ${humanName} called with ${callArgs.length} arguments, expected ${argCount-2}`)}",
      "var destructors=needsDestructorStack?[]:null;var wired=[];var thisWired;",
      'if(isClassMethodFunc){thisWired=argTypes[1]["toWireType"](destructors,this);wired.push(thisWired)}',
      'for(var i=0;i<argCount-2;++i){wired.push(argTypes[i+2]["toWireType"](destructors,callArgs[i]))}',
      "var rv=cppInvokerFunc(cppTargetFunc,...wired);",
      "if(needsDestructorStack){runDestructors(destructors)}else{for(var i=isClassMethodFunc?1:2;i<argTypes.length;++i){",
      "var param=i===1?thisWired:wired[isClassMethodFunc?i-1:i-2];",
      "if(argTypes[i].destructorFunction!==null){argTypes[i].destructorFunction(param)}}}",
      'if(returns){return argTypes[0]["fromWireType"](rv)}};',
      "return createNamedFunction(humanName,invokerFn)}",
    ].join(""),
  },
  {
    name: "__emval_get_method_caller",
    find: "params.push(functionBody);var invokerFunction=newFunc(Function,params)(...args);",
    replace: [
      "var invokerFunction=function(obj,func,destructorsRef,argsPointer){",
      "var callArgs=[];var at=0;",
      'for(var i=0;i<argCount;++i){callArgs.push(types[i].readValueFromPointer(argsPointer+at));at+=types[i]["argPackAdvance"]}',
      "var rv=kind===1?new func(...callArgs):func.call(...(kind===0?[obj,...callArgs]:callArgs));",
      "if(!retType.isVoid){return emval_returnValue(retType,destructorsRef,rv)}};",
    ].join(""),
  },
  {
    // An ES module export. The Vite dev server serves a workspace file as an ES module without CommonJS interop, so
    // `module.exports` gives no factory there. The production bundle converts it.
    name: "export",
    find: "if (typeof exports === 'object' && typeof module === 'object')\n  module.exports = BASIS;\nelse if (typeof define === 'function' && define['amd'])\n  define([], () => BASIS);\n",
    replace: "export default BASIS;\n",
  },
];

const HEADER = `// Generated by packages/assets/src/build/patchBasis.ts from three/examples/jsm/libs/basis/basis_transcoder.js
// (Basis Universal transcoder, Apache-2.0, Binomial LLC; Emscripten glue). Do not edit. The two embind parts that
// call new Function are closures here, so the transcoder runs under the CSP of the app.
/* eslint-disable */
`;

/** The patched transcoder source. Throws when a part to replace is not in the source. */
export function patchedTranscoder(source: string): string {
  let text = source;
  for (const patch of PATCHES) {
    const count = text.split(patch.find).length - 1;
    if (count !== 1) throw new Error(`patch-basis: ${patch.name} found ${String(count)} times (expected 1)`);
    text = text.replace(patch.find, () => patch.replace);
  }
  if (/new Function|newFunc\(Function|\beval\(/.test(text)) {
    throw new Error("patch-basis: the patched transcoder still has dynamic code");
  }
  return HEADER + text;
}

/** Write the copy at `target`, or with `check` only compare it. Returns false when the check finds an old copy. */
export function writeCopy(target: string, check: boolean): boolean {
  const wanted = patchedTranscoder(readFileSync(sourceOf(target), "utf8"));
  if (check) {
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch {
      // A missing file is not current.
    }
    if (current === wanted) return true;
    console.error(`${target} is not current. Run: bun packages/assets/src/build/patchBasis.ts ${target}`);
    return false;
  }
  writeFileSync(target, wanted);
  console.log(`patch-basis: wrote ${target}`);
  return true;
}

if (import.meta.main) {
  const target = process.argv.slice(2).find((arg) => !arg.startsWith("--"));
  if (target === undefined) {
    console.error("usage: bun packages/assets/src/build/patchBasis.ts <target file> [--check]");
    process.exit(2);
  }
  if (!writeCopy(target, process.argv.includes("--check"))) process.exit(1);
}
