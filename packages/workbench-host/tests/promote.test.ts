/**
 * Tests of the promote of a model and of the scratch events of the bridge:
 * - the refusals of the import record (no record, a failed or an over-budget import; incomplete rights do not
 *   refuse), and the target of a project;
 * - the dry run that writes nothing;
 * - the real run that writes the model, the asset record, the rights record of the imports and the entity of the
 *   scene document (the release gate stops the new asset);
 * - the request `asset.promote` and the lab event.
 *
 * No run writes a Claude prompt. Each write goes to a temp project. The promote of the built-in project of this
 * checkout is in the tests of its host plugin (plugins/<name>/host/tests/promote.test.ts).
 */
