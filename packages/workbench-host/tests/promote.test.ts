// The built-in project of the host is the lab fixture (a lab surface, the `labs` runs, the stop gate).
useLabFixture();

const ID = "lx0abc-0011aabb";
const SOURCE = "Generated by code in this repository (the promote test)";
const LICENCE = "Own work of Snowpine; no third-party content";
const BOX_GLB = join(REPO_ROOT, "packages/assets/tests/fixtures/import/box.glb");

const made: string[] = [];
afterAll(() => {
  for (const dir of made) rmSync(dir, { recursive: true, force: true });
});
// The run tests set the plugins of a project with no host plugin; the next test gets the built-in plugins again.
afterEach(() => useHostPlugins(null));

function record(overrides: Record<string, unknown> = {}): Record<string, unknown> {
  return {
    name: "Chair (v2).glb",
    source: SOURCE,
    licence: LICENCE,
    input: "",
    error: null,
    result: { pass: true, extent: [0.4, 0.8, 0.4], tiers: { high: { triangles: 12, bytes: 1_024 } } },
    ...overrides,
  };
}

const EVENT: BridgePromoteEvent = {
  workbench: 1,
  event: "promote",
  import: ID,
  scratch: "scratch-1",
  at: [0.5, 0, 1.25],
  turnDeg: 90,
  dry: true,
};

describe("the plan of a promote", () => {
  test("refuses a model without a record, a failed import and an import over the budget; rights do not refuse", () => {
    expect(promoteRefusal(null)).toContain("no record");
    expect(promoteRefusal(record({ result: null, error: "Blender failed" }))).toBe(
      "The import failed: Blender failed.",
    );
    expect(promoteRefusal(record({ result: { pass: false } }))).toContain("over the budget");
    const over = {
      pass: false,
      tiers: {
        high: {
          ...{ triangles: 52_000, bytes: 2_048_000, maxTextureSize: 4096, pass: false },
          budget: { triangles: 40_000, bytes: 1_536_000, maxTextureSize: 2048 },
        },
      },
      validator: { errors: ["ACCESSOR_INVALID"], warnings: 0 },
    };
    expect(budgetLines(record({ result: over }))).toEqual([
      "high: 52000 of 40000 triangles, 2000 of 1500 KB, texture 4096 of 2048 px OVER",
      "validator: ACCESSOR_INVALID",
    ]);
    expect(promoteRefusal(record({ result: over }))).toContain("(high: 52000 of 40000 triangles");
    // The release gate stops an asset with unknown rights. The promote itself continues.
    expect(promoteRefusal(record({ source: "", licence: "" }))).toBeNull();
  });

  test("names the model file after the drop", () => {
    expect(modelFileName("Chair (v2).glb")).toBe("Chair__v2_.glb");
    expect(modelFileName("lamp.fbx")).toBe("lamp.glb");
  });
});

/** A temp project (the release rules of the showroom, one scene) and an import of the host state. */
function setup(rec: Record<string, unknown> | null) {
  const root = mkdtempSync(join(tmpdir(), "promote-"));
  made.push(root);
  const project = join(root, "project");
  const imports = join(root, "imports");
  mkdirSync(join(project, "scenes"), { recursive: true });
  mkdirSync(join(imports, ID), { recursive: true });
  const doc = {
    ...{ format: "scenity.project/1", id: "garden", name: "Garden", assets: ["assets"] },
    ...{ scenes: ["scenes/main.scene.json"], release: { licences: { allow: ["CC0-1.0"] } } },
  };
  writeFileSync(join(project, "scenity.project.json"), JSON.stringify(doc));
  const scene = {
    format: "scenity.scene/1",
    id: "main",
    entities: { floor: { parent: null, index: 0, components: { transform: { position: [0, 0, 0] } } } },
  };
  writeFileSync(join(project, "scenes/main.scene.json"), JSON.stringify(scene));
  copyFileSync(BOX_GLB, join(imports, ID, "normalized.glb"));
  if (rec !== null) writeFileSync(join(imports, ID, "record.json"), JSON.stringify(rec));
  const events: HostEvent[] = [];
  const deps: PromoteDeps = {
    importsDir: imports,
    current: () => project,
    project: () => ({ dir: project, manifest: join(project, "scenity.project.json") }),
    broadcast: (event) => events.push(event),
  };
  useHostPlugins([]);
  return { project, deps, events };
}

describe("the run of a promote", () => {
  test("a dry run gives the changes and writes nothing", async () => {
    const { project, deps, events } = setup(record());
    const result = await promoteImport(deps, { import: ID, at: [0.5, 0, 1.25], turnDeg: 90, dry: true });
    expect(result).toMatchObject({ dry: true, refused: null, asset: null, entity: null, followUp: [] });
    expect(result.changes).toEqual([
      "assets/sources/Chair__v2_.glb: the model (a free name when the file exists)",
      "assets/sources/Chair__v2_.glb.meta.json: the asset record (the importer of the file, a new asset ID)",
      "rights/imports.yaml: the rights record of the imports (licence not known, webDelivery pending; the release " +
        `gate stops the asset; the answers of the drop: "${SOURCE}", "${LICENCE}")`,
      'scenes/main.scene.json: an entity "Chair (v2)" with a model of the new asset at [0.5, 0, 1.25] turned 90°',
    ]);
    expect(existsSync(join(project, "assets"))).toBe(false);
    expect(events).toEqual([]);
  });

  test("a real run makes the asset, its record, the rights record and the entity; the release gate stops it", async () => {
    const { project, deps, events } = setup(record());
    const result = await promoteImport(deps, { import: ID, at: [0.5, 0, 1.25], turnDeg: 90, dry: false });
    expect(result.refused).toBeNull();
    const id = result.asset?.id ?? "";
    expect(result.asset).toEqual({
      id,
      source: "assets/sources/Chair__v2_.glb",
      record: "assets/sources/Chair__v2_.glb.meta.json",
    });
    expect(readFileSync(join(project, "assets/sources/Chair__v2_.glb"))).toEqual(readFileSync(BOX_GLB));
    const meta = JSON.parse(readFileSync(join(project, "assets/sources/Chair__v2_.glb.meta.json"), "utf8")) as Record<
      string,
      unknown
    >;
    expect(meta).toMatchObject({
      id,
      kind: "model",
      rights: "../../rights/imports.yaml",
      tags: ["imported", "promoted"],
    });
    expect(readFileSync(join(project, "rights/imports.yaml"), "utf8")).toContain("webDelivery: pending");
    expect(result.rights).toMatchObject({ record: "rights/imports.yaml", blocked: true });
    expect(result.rights?.note).toContain("the release gate stops the asset");
    // The entity: one add op of entity.add with the turn, saved in the canonical form.
    expect(result.entity).toEqual({ id: "chair-v2", scene: "scenes/main.scene.json" });
    const scene = JSON.parse(readFileSync(join(project, "scenes/main.scene.json"), "utf8")) as {
      entities: Record<string, { name?: string; parent: null; index: number; components: Record<string, unknown> }>;
    };
    expect(scene.entities["chair-v2"]).toEqual({
      name: "Chair (v2)",
      parent: null,
      index: 1,
      components: {
        model: { asset: `asset:${id}` },
        transform: { position: [0.5, 0, 1.25], rotation: [0, 0.707107, 0, 0.707107] },
      },
    });
    expect(events.map((event) => [event.type, "path" in event ? event.path : null])).toEqual([
      ["scene.saved", "scenes/main.scene.json"],
    ]);
    expect(JSON.stringify(result)).not.toContain("prompt");
    const gate = await releaseCheck(project);
    expect(gate.passed).toBe(false);
    expect(gate.findings.some((finding) => finding.level === "error" && finding.assets.includes(id))).toBe(true);
  });

  test("a second promote of the same import gets a free file name and a free entity ID", async () => {
    const { project, deps } = setup(record());
    await promoteImport(deps, { import: ID, at: [0, 0, 0], turnDeg: 0, dry: false });
    const second = await promoteImport(deps, { import: ID, at: [1, 0, 0], turnDeg: 0, dry: false });
    expect(second.asset?.source).toBe("assets/sources/Chair__v2_-2.glb");
    expect(second.entity?.id).toBe("chair-v2-2");
    expect(existsSync(join(project, "assets/sources/Chair__v2_-2.glb.meta.json"))).toBe(true);
  });

  test("a refused import writes nothing", async () => {
    const { project, deps } = setup(record({ result: null, error: "no model" }));
    const result = await promoteImport(deps, { import: ID, at: [0, 0, 0], turnDeg: 0, dry: false });
    expect(result).toMatchObject({ refused: "The import failed: no model.", asset: null, entity: null });
    expect(existsSync(join(project, "assets"))).toBe(false);
  });
});

describe("the request asset.promote and the lab event", () => {
  const client: PageClient = { id: 1, origin: null, role: "admin", send: () => undefined };

  test("the request promotes; a viewer cannot send it; bad parameters are an error", async () => {
    const { project, deps } = setup(record());
    const router = new Router();
    addPromoteHandler(router, deps);
    const request = { id: 3, type: "asset.promote", import: ID, at: [0.2, 0, -0.4], turnDeg: 0, dry: false };
    const answer = (await router.dispatch(JSON.stringify(request), client)) as { ok: boolean; result: PromoteResult };
    expect(answer.ok).toBe(true);
    expect(answer.result.entity?.id).toBe("chair-v2");
    expect(readFileSync(join(project, "scenes/main.scene.json"), "utf8")).toContain(
      `asset:${answer.result.asset?.id ?? ""}`,
    );
    const bad = await router.dispatch(JSON.stringify({ id: 4, type: "asset.promote", import: "../x" }), client);
    expect(bad).toMatchObject({ id: 4, ok: false });
    expect(requestRefusal("viewer", "asset.promote")).toContain('cannot send "asset.promote"');
    expect(requestRefusal("editor", "asset.promote")).toBeNull();
  });

  test("the promote event of the lab answers promoteResult with the asset and the entity, and no prompt", async () => {
    const { deps } = setup(record({ licence: "" }));
    const answers: [string, unknown][] = [];
    const typed: string[] = [];
    const edit: SceneEditDeps = {
      ...deps,
      terminals: { claudeTerminals: () => [], input: (_id, data) => typed.push(data) },
      chat: { live: () => [], get: () => ({ prompt: () => undefined }) },
      runs: { start: () => ({ run: "r1", done: Promise.resolve({ status: "passed", summary: "" } as RunResult) }) },
      lab: () => ({
        call: (call, args) => {
          answers.push([call, args?.[0]]);
          return Promise.resolve(null);
        },
      }),
    };
    sceneEditEvents(edit)("lab", "visible", { ...EVENT, dry: false });
    for (let i = 0; i < 400 && answers.length === 0; i += 1) await Bun.sleep(10);
    expect(answers[0]?.[0]).toBe("promoteResult");
    const answer = answers[0]?.[1] as PromoteResult;
    expect(answer).toMatchObject({ dry: false, refused: null, entity: { id: "chair-v2" } });
    expect(typed).toEqual([]);
  });
});

describe("the scratch events of the bridge", () => {
  test("checks the fields of the scratch and promote events", () => {
    expect(isBridgeEvent({ workbench: 1, event: "scratch", need: [ID] })).toBe(true);
    expect(isBridgeEvent({ workbench: 1, event: "scratch", need: ["../x"] })).toBe(false);
    expect(isBridgeEvent(EVENT)).toBe(true);
    expect(isBridgeEvent({ ...EVENT, import: "../../etc" })).toBe(false);
    expect(isBridgeEvent({ ...EVENT, at: [0, 0] })).toBe(false);
    expect(isBridgeEvent({ ...EVENT, scratch: "lantern" })).toBe(false);
  });

  test("the picked block of a scratch prop names its import and the gap of its rights", () => {
    const picked = {
      kind: "scratch",
      id: "scratch-1",
      place: { x: 0.5, y: 0, z: 1.25, yawDeg: 15 },
      scratch: { import: ID, name: "chair.glb", source: "made by me", licence: "", rightsGap: "no licence" },
      warnings: [],
    };
    const lines = pickedBlock(REPO_ROOT, picked).join("\n");
    expect(lines).toContain("Picked: scratch scratch-1");
    expect(lines).toContain(
      `import ${ID} (chair.glb): source "made by me", licence "" — rights not allowed: no licence`,
    );
    // The file lines behind a pick come from the host plugin (`paths.picked`). The lab fixture gives none.
    expect(lines).not.toContain("undefined");
  });
});
