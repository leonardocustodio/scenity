/**
 * Output formats of the token build. Style Dictionary resolves and transforms the
 * tokens of each variant. These functions then write one file for all variants: the CSS variables, the
 * Tailwind 4 theme, the TypeScript constants, the Android resources, the Compose object, the Unreal CSV
 * and the token reference of the gallery.
 */

import type { ContrastResult, DistinctResult } from "../src/checks";
import type { TokenReference } from "../src/reference";
import { numberValue, type TokenType } from "./values";
import { DEFAULT_THEME, type Variant } from "./variants";

export type Tier = "primitive" | "semantic" | "component";

export interface TokenRecord {
  /** The dotted token path, for example color.surface.base. */
  readonly name: string;
  readonly path: readonly string[];
  readonly type: TokenType;
  readonly tier: Tier;
  readonly description: string | null;
  /** True for a token whose change needs the approval of the owners of its domain (the `guarded` extension). */
  readonly guarded: boolean;
  /** The org.scenity extension of the token, for example the sound bus. */
  readonly extension: Readonly<Record<string, unknown>>;
  /** True for a token of the base set (the engine) in the build of a plugin set. */
  readonly base: boolean;
  /** The CSS value of the token in each variant, by variant ID. */
  readonly values: Readonly<Record<string, string>>;
}

export interface BuildModel {
  /** The package of the outputs, for example @scenity/tokens. */
  readonly name: string;
  readonly version: string;
  /** True for a plugin set: tokens.css and tailwind.css hold only the tokens of the plugin. */
  readonly extends: boolean;
  readonly variants: readonly Variant[];
  /** All tokens, sorted by name. */
  readonly tokens: readonly TokenRecord[];
}

export const HEADER = (model: Pick<BuildModel, "name" | "version">): string =>
  `${model.name} ${model.version}. Generated by the token build of @scenity/tokens (config/build.ts). Do not edit.`;

export function cssVarName(token: Pick<TokenRecord, "path">): string {
  return `--sc-${token.path.join("-")}`;
}

/** True if the value of the token is not the same in all variants. */
export function isThemed(token: TokenRecord, variants: readonly Variant[]): boolean {
  const first = token.values[variants[0]?.id ?? ""];
  return variants.some((v) => token.values[v.id] !== first);
}

/** True for a token of the CSS and of the TypeScript constants for components: not a primitive color or a sound. */
export function inCss(token: TokenRecord): boolean {
  return !(token.tier === "primitive" && token.type === "color") && token.path[0] !== "sound";
}

function standardOf(variant: Variant, variants: readonly Variant[]): Variant | undefined {
  return variants.find((v) => v.theme === variant.theme && v.contrast === "standard");
}

// ---------------------------------------------------------------------------------------------- CSS

function selectorOf(variant: Variant): string {
  const theme = `[data-theme="${variant.theme}"]`;
  if (variant.contrast === "more") return `${theme}[data-contrast="more"],\n[data-contrast="more"] ${theme}`;
  return variant.theme === DEFAULT_THEME ? `:root,\n${theme}` : theme;
}

/** The tokens of the CSS outputs. In the build of a plugin set, only the tokens of the plugin. */
function cssTokens(model: BuildModel): TokenRecord[] {
  return model.tokens.filter((t) => inCss(t) && !t.base);
}

export function formatCss(model: BuildModel): string {
  const tokens = cssTokens(model);
  const lines: string[] = [`/* ${HEADER(model)} */`, ""];
  const shared = tokens.filter((t) => !isThemed(t, model.variants));
  const firstId = model.variants[0]?.id ?? "";
  if (!model.extends || shared.length > 0) {
    lines.push(":root {");
    for (const t of shared) lines.push(`  ${cssVarName(t)}: ${t.values[firstId] ?? ""};`);
    lines.push("}", "");
  }
  // The default theme comes first, so a [data-theme] block of the same specificity wins over :root.
  const ordered = [...model.variants].sort(
    (a, b) =>
      Number(a.contrast === "more") - Number(b.contrast === "more") ||
      Number(b.theme === DEFAULT_THEME) - Number(a.theme === DEFAULT_THEME),
  );
  for (const variant of ordered) {
    const standard = standardOf(variant, model.variants);
    const themed = tokens.filter((t) => isThemed(t, model.variants));
    // A high-contrast block holds only the values that differ from the standard variant of its theme.
    const own =
      variant.contrast === "more" && standard
        ? themed.filter((t) => t.values[variant.id] !== t.values[standard.id])
        : themed;
    // The CSS of a plugin set adds variables to the blocks of the engine CSS: no color scheme and no empty block.
    if (model.extends && own.length === 0) continue;
    lines.push(`${selectorOf(variant)} {`);
    if (variant.contrast === "standard" && !model.extends) lines.push(`  color-scheme: ${variant.scheme};`);
    for (const t of own) lines.push(`  ${cssVarName(t)}: ${t.values[variant.id] ?? ""};`);
    lines.push("}", "");
  }
  return lines.join("\n");
}

// ----------------------------------------------------------------------------------------- Tailwind

const WEIGHT_NAMES: Readonly<Record<string, string>> = {
  "400": "normal",
  "500": "medium",
  "600": "semibold",
  "650": "strong",
  "700": "bold",
};

/** The Tailwind theme variable of a token, or null if the token has no utility. */
export function tailwindVariable(token: TokenRecord): { name: string; literal: boolean } | null {
  const [head, ...rest] = token.path;
  const tail = rest.join("-");
  if (token.tier === "primitive") {
    if (head === "font" && rest[0] === "family") return { name: `--font-${rest.slice(1).join("-")}`, literal: false };
    if (head === "font" && rest[0] === "weight" && rest[1] !== undefined) {
      const alias = WEIGHT_NAMES[rest[1]];
      return alias === undefined ? null : { name: `--font-weight-${alias}`, literal: false };
    }
    return null;
  }
  if (token.tier === "component") return null;
  switch (head) {
    case "color":
      return { name: `--color-${tail}`, literal: false };
    case "radius":
      return { name: `--radius-${tail}`, literal: false };
    case "shadow":
      return { name: `--shadow-${tail}`, literal: false };
    case "ease":
      return { name: `--ease-${tail}`, literal: false };
    case "duration":
      return { name: `--transition-duration-${tail}`, literal: false };
    case "size":
      return { name: `--spacing-${tail}`, literal: false };
    case "type": {
      const [role, part] = rest;
      if (role === undefined) return null;
      const suffix: Record<string, string> = {
        size: "",
        "line-height": "--line-height",
        weight: "--font-weight",
        tracking: "--letter-spacing",
      };
      const s = part === undefined ? undefined : suffix[part];
      return s === undefined ? null : { name: `--text-${role}${s}`, literal: false };
    }
    // Media and container queries cannot read CSS variables, so breakpoints and containers are literal.
    case "bp":
      return rest[0] === "short" ? null : { name: `--breakpoint-${tail}`, literal: true };
    case "layout":
      return { name: `--container-${tail.replace(/-max$/, "")}`, literal: true };
    default:
      return null;
  }
}

/** The theme lines of the utilities of the CSS tokens. */
function tailwindLines(model: BuildModel): string[] {
  const firstId = model.variants[0]?.id ?? "";
  const lines: string[] = [];
  for (const token of cssTokens(model)) {
    const variable = tailwindVariable(token);
    if (variable === null) continue;
    const value = variable.literal ? (token.values[firstId] ?? "") : `var(${cssVarName(token)})`;
    lines.push(`  ${variable.name}: ${value};`);
  }
  return lines;
}

/** The Tailwind theme of a plugin set: the utilities of the plugin tokens, after the theme of the engine. */
function formatTailwindExtension(model: BuildModel): string {
  return [
    `/* ${HEADER(model)} */`,
    "/* Tailwind 4 utilities of the plugin tokens. Import this file after the tailwind.css of @scenity/tokens. */",
    "",
    "@theme inline {",
    ...tailwindLines(model),
    "}",
    "",
  ].join("\n");
}

export function formatTailwind(model: BuildModel): string {
  if (model.extends) return formatTailwindExtension(model);
  const lines: string[] = [
    `/* ${HEADER(model)} */`,
    "/* Tailwind 4 theme of Scenity: utilities map to the semantic tokens of tokens.css. */",
    "/* It removes the default palette, radii, shadows, fonts, easings, durations and breakpoints, so only */",
    "/* token utilities exist for them. The default text sizes and containers stay for layout code. */",
    "",
    "@theme inline {",
    "  --color-*: initial;",
    "  --radius-*: initial;",
    "  --shadow-*: initial;",
    "  --font-*: initial;",
    "  --breakpoint-*: initial;",
    "  --ease-*: initial;",
    "  --transition-duration-*: initial;",
    "  --spacing: var(--sc-space-1);",
  ];
  lines.push(...tailwindLines(model));
  lines.push("}", "");
  lines.push(
    "/* Variants for the theme attributes of the root element (README: Themes). */",
    '@custom-variant theme-navy (&:where([data-theme="navy"], [data-theme="navy"] *));',
    '@custom-variant theme-light (&:where([data-theme="light"], [data-theme="light"] *));',
    '@custom-variant theme-dark (&:where([data-theme="dark"], [data-theme="dark"] *));',
    '@custom-variant contrast-more (&:where([data-contrast="more"], [data-contrast="more"] *));',
    "/* Reduced motion from the operating system or from the in-app setting (data-motion). */",
    "@custom-variant reduce-motion {",
    "  @media (prefers-reduced-motion: reduce) {",
    "    @slot;",
    "  }",
    '  &:where([data-motion="reduced"], [data-motion="reduced"] *) {',
    "    @slot;",
    "  }",
    "}",
    "",
  );
  return lines.join("\n");
}

// --------------------------------------------------------------------------------------- TypeScript

function camel(text: string): string {
  return text.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
}

export function formatTypeScript(model: BuildModel): string {
  const tokens = model.tokens.filter((t) => !(t.tier === "primitive" && t.type === "color"));
  const themes = [...new Set(model.variants.map((v) => v.theme))];
  const q = (s: string): string => JSON.stringify(s);
  const out: string[] = [
    `// ${HEADER(model)}`,
    "// Typed token values for code that cannot read CSS variables, for example canvas renderers and audio",
    "// engines.",
    "",
    `export const TOKENS_VERSION = ${q(model.version)};`,
    "",
    `export const THEME_NAMES = [${themes.map(q).join(", ")}] as const;`,
    "export type ThemeName = (typeof THEME_NAMES)[number];",
    'export type Contrast = "standard" | "more";',
    `export const THEME_VARIANTS = [${model.variants.map((v) => q(v.id)).join(", ")}] as const;`,
    "export type ThemeVariant = (typeof THEME_VARIANTS)[number];",
    `export const DEFAULT_THEME: ThemeName = ${q(DEFAULT_THEME)};`,
    "",
    `export type TokenType = ${[...new Set(tokens.map((t) => t.type))].sort().map(q).join(" | ")};`,
    "",
    "export type TokenName =",
    ...tokens.map((t, i) => `  | ${q(t.name)}${i === tokens.length - 1 ? ";" : ""}`),
    "",
    "export interface TokenInfo {",
    "  readonly type: TokenType;",
    "  /** The CSS custom property, or null for a token that is not in tokens.css. */",
    "  readonly cssVar: string | null;",
    "  /** A change to a guarded token needs the approval of the owners of its domain and UX. */",
    "  readonly guarded: boolean;",
    "  /** True if the value depends on the theme variant. */",
    "  readonly themed: boolean;",
    "}",
    "",
    "export const TOKEN_INFO: Readonly<Record<TokenName, TokenInfo>> = {",
  ];
  for (const t of tokens) {
    const cssVar = inCss(t) ? q(cssVarName(t)) : "null";
    out.push(
      `  ${q(t.name)}: { type: ${q(t.type)}, cssVar: ${cssVar}, guarded: ${String(t.guarded)}, themed: ${String(isThemed(t, model.variants))} },`,
    );
  }
  out.push("};", "");
  const firstId = model.variants[0]?.id ?? "";
  out.push("const SHARED: Readonly<Partial<Record<TokenName, string>>> = {");
  for (const t of tokens.filter((t) => !isThemed(t, model.variants))) {
    out.push(`  ${q(t.name)}: ${q(t.values[firstId] ?? "")},`);
  }
  out.push("};", "");
  out.push("const THEMED: Readonly<Record<ThemeVariant, Readonly<Partial<Record<TokenName, string>>>>> = {");
  for (const v of model.variants) {
    out.push(`  ${q(v.id)}: {`);
    for (const t of tokens.filter((t) => isThemed(t, model.variants))) {
      out.push(`    ${q(t.name)}: ${q(t.values[v.id] ?? "")},`);
    }
    out.push("  },");
  }
  out.push("};", "");
  out.push(
    "/** Return the variant ID of a theme and a contrast preference. */",
    'export function themeVariant(theme: ThemeName, contrast: Contrast = "standard"): ThemeVariant {',
    '  return contrast === "more" ? `${theme}-high-contrast` : theme;',
    "}",
    "",
    "/** Return the CSS text of a token in a theme variant, for example #4ade80 or 200ms. */",
    "export function tokenValue(theme: ThemeVariant, name: TokenName): string {",
    "  const value = THEMED[theme][name] ?? SHARED[name];",
    "  if (value === undefined) throw new Error(`unknown token: ${name}`);",
    "  return value;",
    "}",
    "",
    "/**",
    " * Return the number of a token: px for a dimension (1 rem is 16 px), ms for a duration, the number for a",
    " * number or a font weight. Throw an error for a token without a single number (a color or a shadow).",
    " */",
    "export function tokenNumber(theme: ThemeVariant, name: TokenName): number {",
    "  const text = tokenValue(theme, name);",
    "  const match = /^(-?\\d+(?:\\.\\d+)?)(px|rem|ms|em)?$/.exec(text);",
    "  if (match?.[1] === undefined) throw new Error(`token ${name} has no number: ${text}`);",
    "  const n = Number(match[1]);",
    '  return match[2] === "rem" ? n * 16 : n;',
    "}",
    "",
    "/** Return the CSS custom property of a token, for example --sc-color-channel-ecg. */",
    "export function cssVar(name: TokenName): string {",
    "  const variable = TOKEN_INFO[name].cssVar;",
    "  if (variable === null) throw new Error(`token ${name} is not in tokens.css`);",
    "  return variable;",
    "}",
    "",
  );
  out.push(...soundLines(tokens, firstId));
  return out.join("\n");
}

/**
 * The sound tokens in groups, one group for each sound. Durations are in ms. A set without sound tokens has no lines.
 */
function soundLines(tokens: readonly TokenRecord[], firstId: string): string[] {
  const q = (s: string): string => JSON.stringify(s);
  const groups = new Map<string, TokenRecord[]>();
  for (const t of tokens.filter((t) => t.path[0] === "sound")) {
    const key = t.path.slice(1, 3).join(".");
    groups.set(key, [...(groups.get(key) ?? []), t]);
  }
  if (groups.size === 0) return [];
  const out: string[] = [];
  out.push(
    "export interface SoundToken {",
    "  /** The audio bus, for example voice, ambience or ui. */",
    "  readonly bus: string;",
    "  readonly timbre: string | null;",
    "  /** Pulses per group, for example [3, 2, 3, 2] for a high-priority alarm burst. */",
    "  readonly pattern: readonly number[] | null;",
    "  /** A recorded sound file, if the sound is not only synthesized. */",
    "  readonly asset: string | null;",
    "  readonly guarded: boolean;",
    "  /** Frequencies in Hz, durations in ms, gains as factors. */",
    "  readonly values: Readonly<Record<string, number>>;",
    "}",
    "",
    "export const SOUND = {",
  );
  for (const [key, group] of groups) {
    const ext = group[0]?.extension.sound as Record<string, unknown> | undefined;
    const pattern = Array.isArray(ext?.pattern) ? `[${(ext.pattern as number[]).join(", ")}]` : "null";
    const values = group
      .map((t) => `${q(camel(t.path.slice(3).join("-")))}: ${String(numberValue(t.values[firstId] ?? "") ?? 0)}`)
      .join(", ");
    out.push(
      `  ${q(key)}: { bus: ${q(typeof ext?.bus === "string" ? ext.bus : "")}, timbre: ${typeof ext?.timbre === "string" ? q(ext.timbre) : "null"}, pattern: ${pattern}, asset: ${typeof ext?.asset === "string" ? q(ext.asset) : "null"}, guarded: ${String(group.some((t) => t.guarded))}, values: { ${values} } },`,
    );
  }
  out.push(
    "} as const satisfies Readonly<Record<string, SoundToken>>;",
    "",
    "export type SoundName = keyof typeof SOUND;",
    "",
  );
  return out;
}

// ---------------------------------------------------------------------------------------- Reference

export function formatReference(
  model: BuildModel,
  contrast: readonly ContrastResult[],
  distinct: readonly DistinctResult[],
): string {
  const reference: TokenReference = {
    version: model.version,
    variants: model.variants.map((v) => ({ id: v.id, theme: v.theme, contrast: v.contrast, scheme: v.scheme })),
    tokens: model.tokens.map((t) => ({
      name: t.name,
      type: t.type,
      tier: t.tier,
      css_var: inCss(t) ? cssVarName(t) : null,
      guarded: t.guarded,
      themed: isThemed(t, model.variants),
      description: t.description,
      values: t.values,
    })),
    contrast,
    distinct,
  };
  return `${JSON.stringify(reference, null, 2)}\n`;
}
