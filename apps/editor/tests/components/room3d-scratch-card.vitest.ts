// The scratch prop part of the selection card: the import facts, and the "rights not known" mark (a missing answer, or
// the reason of the licence register). Also Duplicate and Delete, and "Promote to the room": the dry run with its
// changes, the promote, the rights note and the code change, with no Claude prompt.
import { mount } from "@vue/test-utils";
import { describe, expect, it } from "vitest";
import ScratchCard from "../../src/core/scratch/ScratchCard.vue";
import type { PromoteView } from "../../src/core/scratch/scratchInfo";
import type { ScratchItem } from "../../src/core/scratch/useScratch";

const ITEM: ScratchItem = {
  id: "scratch-1",
  model: "lx0abc-0011aabb",
  at: [0.5, 0, 1.2],
  turnDeg: 15,
  loaded: true,
  error: null,
  info: {
    import: "lx0abc-0011aabb",
    name: "chair.glb",
    source: "Generated by code in this repository (a test)",
    licence: "Own work of Snowpine; no third-party content",
    rights: { allowed: true, reason: null },
    pass: true,
    triangles: 188,
    kb: 7,
    warnings: [],
  },
};

function card(props: Partial<InstanceType<typeof ScratchCard>["$props"]> = {}) {
  return mount(ScratchCard, { props: { item: ITEM, inWorkbench: true, promotion: null, ...props } });
}

describe("ScratchCard", () => {
  it("shows the import, the budget and the rights, and asks for a dry promote", async () => {
    const wrapper = card();
    expect(wrapper.text()).toContain("Scratch prop of chair.glb");
    expect(wrapper.get('[data-testid="lab-scratch-budget"]').text()).toBe("188 triangles, 7 KB · in the prop budget");
    expect(wrapper.get('[data-testid="lab-scratch-licence"]').text()).toBe(
      "Own work of Snowpine; no third-party content",
    );
    expect(wrapper.find('[data-testid="lab-scratch-rights"]').exists()).toBe(false);
    await wrapper.get('[data-testid="lab-scratch-promote"]').trigger("click");
    await wrapper.get('[data-testid="lab-scratch-duplicate"]').trigger("click");
    await wrapper.get('[data-testid="lab-scratch-delete"]').trigger("click");
    expect(wrapper.emitted("promote")).toEqual([[true]]);
    expect(wrapper.emitted("duplicate")).toHaveLength(1);
    expect(wrapper.emitted("remove")).toHaveLength(1);
  });

  it("marks incomplete rights, and the promote stays open (the release gate stops the asset)", () => {
    const info = { ...ITEM.info!, licence: "" };
    const wrapper = card({ item: { ...ITEM, info } });
    expect(wrapper.get('[data-testid="lab-scratch-rights"]').text()).toContain("Rights not known: no licence");
    expect(wrapper.get('[data-testid="lab-scratch-rights"]').text()).toContain("the release gate");
    expect(wrapper.get('[data-testid="lab-scratch-licence"]').text()).toBe("not given");
    expect(wrapper.get('[data-testid="lab-scratch-promote"]').attributes("disabled")).toBeUndefined();
  });

  it("shows why the licence register does not allow the source, and refuses a model over the budget", () => {
    const reason = 'the source "Sketchfab" is not in the licence register (allowed: Reallusion ActorCore)';
    const info = { ...ITEM.info!, source: "Sketchfab", rights: { allowed: false, reason } };
    const wrapper = card({ item: { ...ITEM, info } });
    expect(wrapper.get('[data-testid="lab-scratch-rights"]').text()).toContain(`Rights not known: ${reason}`);
    const over = card({ item: { ...ITEM, info: { ...ITEM.info!, pass: false } } });
    const promote = over.get('[data-testid="lab-scratch-promote"]');
    expect(promote.attributes("disabled")).toBeDefined();
    expect(promote.attributes("title")).toBe("the model is not in the budget");
  });

  it("shows the changes of a dry run with no prompt, then promotes and shows the result", async () => {
    const promotion: PromoteView = {
      id: "scratch-1",
      dry: true,
      status: "done",
      refused: null,
      changes: ["art/props/imports/drop/chair.glb: the model"],
      asset: null,
      entity: null,
      rights: "",
      followUp: [],
    };
    const wrapper = card({ promotion });
    expect(wrapper.get('[data-testid="lab-promote-changes"]').text()).toContain("imports/drop/chair.glb");
    expect(wrapper.text()).toContain("no Claude prompt");
    expect(wrapper.find('[data-testid="lab-promote-prompt"]').exists()).toBe(false);
    await wrapper.get('[data-testid="lab-promote-send"]').trigger("click");
    expect(wrapper.emitted("promote")).toEqual([[false]]);
    const done = card({
      promotion: {
        ...promotion,
        dry: false,
        changes: ["scenes/room.scene.json: the entity chair"],
        asset: "01ASSET",
        entity: "chair",
        rights: "art/props/rights/imports.yaml: the release gate stops the asset until the owner records its rights.",
        followUp: ["The room kit shows only the prop slots of PROP_SLOTS"],
      },
    });
    expect(done.text()).toContain("Promoted: entity chair.");
    expect(done.get('[data-testid="lab-promote-done"]').text()).toContain("room.scene.json");
    expect(done.get('[data-testid="lab-promote-rights"]').text()).toContain("release gate");
    expect(done.get('[data-testid="lab-promote-follow"]').text()).toContain("PROP_SLOTS");
    expect(done.find('[data-testid="lab-promote-send"]').exists()).toBe(false);
  });

  it("needs the workbench host for a promote", () => {
    const wrapper = card({ inWorkbench: false });
    expect(wrapper.get('[data-testid="lab-scratch-promote"]').attributes("disabled")).toBeDefined();
    expect(wrapper.text()).toContain("the promote needs the workbench host");
  });
});
